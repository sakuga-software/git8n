/** A table cell holds one line, and a `|` ends the cell. */
const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

const typeOf = (schema: JsonSchema): string => {
  if (schema.enum) return schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(', ');
  if (schema.type === 'array') return `array of ${schema.items ? typeOf(schema.items) : 'values'}`;

  return schema.type ?? 'any';
};

/** The limits of a field that its description does not say. */
const limitsOf = (schema: JsonSchema): string[] => {
  const limits: string[] = [];

  if (schema.default !== undefined) limits.push(`Default: \`${JSON.stringify(schema.default)}\`.`);
  if (schema.pattern) limits.push(`Matches \`${schema.pattern}\`.`);
  if (schema.minLength) limits.push(`At least ${schema.minLength} character.`);
  if (schema.minimum !== undefined && schema.minimum > 0) limits.push(`At least ${schema.minimum}.`);
  if (schema.minItems !== undefined && schema.maxItems !== undefined) {
    limits.push(`From ${schema.minItems} to ${schema.maxItems} items.`);
  }

  return limits;
};

const fieldsOf = (schema: JsonSchema, title: string): string[] => {
  const properties = Object.entries(schema.properties ?? {});

  if (properties.length === 0) return ['**Input:** none.'];

  const required = new Set(schema.required ?? []);
  const nested: string[] = [];
  const rows = properties.map(([name, field]) => {
    if (field.type === 'array' && field.items?.properties) {
      nested.push('', `Each item of \`${name}\`:`, '', ...fieldsOf(field.items, '').slice(2));
    }

    const what = [field.description ?? '', ...limitsOf(field)].filter(Boolean).join(' ');

    return `| \`${name}\` | ${cell(typeOf(field))} | ${required.has(name) ? 'yes' : 'no'} | ${cell(what)} |`;
  });

  return [title, '', '| Field | Type | Required | What it is |', '| --- | --- | --- | --- |', ...rows, ...nested];
};

const accessOf = (tool: Tool): string =>
  tool.annotations?.readOnlyHint
    ? '<Badge type="tip" text="read-only" />'
    : '<Badge type="warning" text="writes" /> It writes a commit on the repository, and deletes nothing.';

/** The Markdown of the page, from the tools that a client lists. */
export const renderReference = (tools: readonly Tool[]): string => {
  const sections = tools.map((tool) => {
    const answer = ANSWERS[tool.name];

    if (answer === undefined) throw new Error(`ANSWERS has no answer for ${tool.name}.`);

    return [
      `## \`${tool.name}\``,
      '',
      accessOf(tool),
      '',
      `**${tool.title ?? tool.name}.** ${tool.description ?? ''}`,
      '',
      ...fieldsOf(tool.inputSchema as JsonSchema, '**Input:**'),
      '',
      answer,
    ].join('\n');
  });

  return `${[INTRO, ...sections].join('\n\n')}\n`;
};

/**
 * The page as `pnpm format` writes it, with the settings of `.oxfmtrc.json`.
 *
 * CI runs `oxfmt --check` on every Markdown file. A page that oxfmt changes fails it, and a page
 * changed by oxfmt is no longer the page of `renderReference`.
 */
export const formatted = async (markdown: string): Promise<string> => {
  const { ignorePatterns: _, ...config } = JSON.parse(
    await readFile(`${ROOT}.oxfmtrc.json`, 'utf8'),
  ) as FormatConfig & {
    ignorePatterns?: string[];
  };
  const { code, errors } = await format('mcp-tools.md', markdown, config);

  if (errors.length > 0) throw new Error(`oxfmt cannot format the page: ${JSON.stringify(errors)}`);

  return code;
};

/** The tools of a server, as a client lists them. No call reaches the API. */
export const listedTools = async (): Promise<Tool[]> => {
  const [serverSide, clientSide] = InMemoryTransport.createLinkedPair();
  const client = new Client({ name: 'git8n-reference', version: '0' });

  await buildServer({ url: 'https://git8n.invalid', token: 'unused' }).connect(serverSide);
  await client.connect(clientSide);

  const { tools } = await client.listTools();

  await client.close();

  return tools;
};

if (import.meta.main) await writeFile(REFERENCE_PATH, await formatted(renderReference(await listedTools())));
