/**
 * Writes `docs/reference/mcp-tools.md` from the tools that the server lists (DB-211, G8N-81).
 *
 * The input of each tool comes from its schema, as an MCP client reads it. The schema does not
 * describe the answer of a tool, so `ANSWERS` holds it. `reference.spec.ts` fails if the page
 * on disk is not the page that this module writes.
 *
 *   pnpm -F @git8n/mcp docs:tools
 */

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));

export const REFERENCE_PATH = new URL('../../../docs/reference/mcp-tools.md', import.meta.url);

interface JsonSchema {
  type?: string;
  description?: string;
  enum?: unknown[];
  default?: unknown;
  pattern?: string;
  minLength?: number;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
  items?: JsonSchema;
  properties?: Record<string, JsonSchema>;
  required?: string[];
}

